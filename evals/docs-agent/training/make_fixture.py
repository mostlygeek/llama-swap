#!/usr/bin/env python3
"""Writes fixture/models.yaml, a training copy of the eval's model fixture.

Training conversations about the running config must not use the eval's fixture:
a model that saw those ids and values could pass the running-config cases from
memory. This keeps the shape, which is what the model should learn, and changes
every id and most numbers. The output is deterministic.

    python3 evals/docs-agent/training/make_fixture.py
"""

import pathlib
import random
import re

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parent / "fixture" / "models.yaml"
TARGET = HERE / "fixture" / "models.yaml"

NAMES = """
aurora borealis cascade delta ember fjord glacier harbor iris juniper kestrel
lagoon meadow nimbus onyx prairie quartz ridge summit tundra umbra vale willow
xenon yarrow zephyr alder birch cedar dune elm fern grove heron indigo jasper
kelp lotus maple nectar oak pine quill reed sage thorn ursa violet wren yew
""".split()

NUMBERS = re.compile(
    r"^(\s*(?:ttl|concurrencyLimit|context|vram_gb|unloadTimeout)\s*:\s*)(\d+)\s*$",
    re.M,
)
FACTORS = [0.25, 0.5, 2, 3, 4]


def main():
    rng = random.Random(1302)
    text = SOURCE.read_text()
    text = text[text.index("models:") :]

    ids = sorted(set(re.findall(r"\beval-[A-Za-z0-9.-]*[A-Za-z0-9]", text)))
    if len(ids) > len(NAMES):
        raise SystemExit(f"need {len(ids)} names, have {len(NAMES)}")
    names = rng.sample(NAMES, len(ids))
    mapping = {old: f"train-{name}" for old, name in zip(ids, names)}

    # Longest first, so one id can never rewrite part of a longer one.
    for old in sorted(ids, key=len, reverse=True):
        text = re.sub(rf"(?<![\w-]){re.escape(old)}(?![\w.-]*[A-Za-z0-9])", mapping[old], text)

    def perturb(match):
        value = int(match.group(2))
        if value <= 0:
            return match.group(0)
        return f"{match.group(1)}{max(1, int(value * rng.choice(FACTORS)))}"

    text = NUMBERS.sub(perturb, text)

    header = (
        "# Generated by make_fixture.py from ../../fixture/models.yaml. Do not edit.\n"
        "# Training conversations use this instead of the eval's fixture, so a model\n"
        "# cannot pass the running-config cases from memory.\n\n"
    )
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(header + text)
    print(f"wrote {TARGET} with {len(ids)} renamed ids")


if __name__ == "__main__":
    main()
